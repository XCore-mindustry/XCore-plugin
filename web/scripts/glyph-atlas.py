"""Builds the sheet of content icons that Mindustry draws for private-use characters in text.

Usage: python3 -I scripts/glyph-atlas.py <Mindustry.jar>
Writes public/sprites/glyphs.webp and src/lib/glyph-cells.ts. The game reads the same
icons/icons.properties and fits each region into a square cell, see Fonts.loadContentIcons.
"""

import io
import struct
import sys
import zipfile
from pathlib import Path

from PIL import Image

CELL = 32
COLUMNS = 32
ROOT = Path(__file__).resolve().parent.parent


def regions(jar: zipfile.ZipFile):
    data = io.BytesIO(jar.read("sprites/sprites.aatls"))
    def read(fmt):
        return struct.unpack(">" + fmt, data.read(struct.calcsize(">" + fmt)))
    def text():
        (n,) = read("H")
        return data.read(n).decode("utf-8")
    assert data.read(5) == b"AATLS"
    data.read(1)
    found = {}
    # Every page starts with a byte that TextureAtlasData reads as its end-of-file check.
    while data.read(1):
        page = text()
        read("hh4b")
        (count,) = read("i")
        for _ in range(count):
            name = text()
            left, top, width, height = read("4h")
            for size in (4, 4, 4):
                if read("?")[0]:
                    read(f"{size}h")
            found[name] = (page, left, top, width, height)
    return found


def main(jar_path: str):
    with zipfile.ZipFile(jar_path) as jar:
        atlas = regions(jar)
        ui_page = atlas["logo"][0]
        page = Image.open(io.BytesIO(jar.read(f"sprites/{ui_page}"))).convert("RGBA")
        icons = []
        for line in jar.read("icons/icons.properties").decode().splitlines():
            code, rest = line.split("=", 1)
            region = atlas.get(rest.split("|")[1])
            # The game skips icons that are not on the UI page, and so do we.
            if region and region[0] == ui_page:
                icons.append((int(code), region))

    rows = -(-len(icons) // COLUMNS)
    sheet = Image.new("RGBA", (COLUMNS * CELL, rows * CELL))
    cells = []
    for i, (code, (_, left, top, width, height)) in enumerate(sorted(icons)):
        icon = page.crop((left, top, left + width, top + height))
        scale = CELL / max(width, height)
        icon = icon.resize((max(1, round(width * scale)), max(1, round(height * scale))), Image.NEAREST)
        x, y = i % COLUMNS * CELL, i // COLUMNS * CELL
        sheet.paste(icon, (x + (CELL - icon.width) // 2, y + (CELL - icon.height) // 2))
        cells.append(f"  [{code}, {i}],")

    sheet.save(ROOT / "public/sprites/glyphs.webp", lossless=True, method=6)
    (ROOT / "src/lib/glyph-cells.ts").write_text(
        "// Generated by scripts/glyph-atlas.py from Mindustry v160. Do not edit.\n"
        "// Character code to cell index in /sprites/glyphs.webp.\n"
        f"export const GLYPH_CELL = {CELL};\nexport const GLYPH_COLUMNS = {COLUMNS};\n"
        f"export const GLYPH_ROWS = {rows};\n"
        "export const glyphCells = new Map<number, number>([\n" + "\n".join(cells) + "\n]);\n"
    )
    print(f"{len(icons)} icons, {rows} rows")


if __name__ == "__main__":
    main(sys.argv[1])
