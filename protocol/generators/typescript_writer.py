"""Write generated TypeScript types for the protocol messages a web client sends or reads."""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from pathlib import Path

from .discovery import GenerationPlan, load_aggregate_generation_plan, repo_root
from .model import FieldShape, FieldType, NormalizedField, NormalizedSchema


@dataclass(frozen=True, slots=True)
class GeneratedFile:
    path: Path
    content: str


@dataclass(frozen=True, slots=True)
class TypeScriptModule:
    file_name: str
    family: str
    # The request message of each RPC route; its response message is emitted too.
    rpc_requests: tuple[str, ...]


TYPESCRIPT_MODULES: tuple[TypeScriptModule, ...] = (
    TypeScriptModule(
        file_name="discord-accounts.ts",
        family="discord",
        rpc_requests=("discord.account.operation.request",),
    ),
)

_SCALAR_TYPES = {
    FieldType.STRING: "string",
    FieldType.INTEGER: "number",
    FieldType.NUMBER: "number",
    FieldType.BOOLEAN: "boolean",
}


def generated_typescript_root() -> Path:
    return repo_root() / "typescript"


def write_typescript_outputs(plan: GenerationPlan) -> tuple[Path, ...]:
    written: list[Path] = []
    for output in render_typescript_outputs(plan):
        output.path.parent.mkdir(parents=True, exist_ok=True)
        output.path.write_text(output.content, encoding="utf-8")
        written.append(output.path)
    return tuple(written)


def check_typescript_outputs(plan: GenerationPlan) -> tuple[Path, ...]:
    return tuple(
        output.path
        for output in render_typescript_outputs(plan)
        if not output.path.exists() or output.path.read_text(encoding="utf-8") != output.content
    )


def render_typescript_outputs(plan: GenerationPlan) -> tuple[GeneratedFile, ...]:
    # Like shared.py, the modules are always rendered from every family, whatever was requested.
    del plan
    aggregate_plan = load_aggregate_generation_plan()
    return tuple(
        GeneratedFile(
            path=generated_typescript_root() / module.file_name,
            content=_render_module(module, aggregate_plan),
        )
        for module in TYPESCRIPT_MODULES
    )


def _render_module(module: TypeScriptModule, plan: GenerationPlan) -> str:
    schemas_by_type = {schema.message_type: schema for schema in plan.message_schemas_for(module.family)}
    routes_by_type = {route.message_type: route for route in plan.routes_for(module.family)}
    shared_by_title = {schema.title: schema for schema in plan.shared_schemas}

    messages: list[NormalizedSchema] = []
    route_blocks: list[str] = []
    for request_type in module.rpc_requests:
        route = routes_by_type[request_type]
        if route.kind != "rpc-request" or route.response is None:
            raise ValueError(f"TypeScript module {module.file_name} expects an RPC route: {request_type}")
        messages.extend((schemas_by_type[request_type], schemas_by_type[route.response.message_type]))
        route_blocks.append(
            "\n".join(
                [
                    f"export const {_constant_name(request_type, route.message_version)}_ROUTE = {{",
                    f"  messageType: {json.dumps(route.message_type)},",
                    f"  messageVersion: {route.message_version},",
                    f"  stream: {json.dumps(route.stream)},",
                    f"  ttlMs: {route.ttl_ms},",
                    f"  responseMessageType: {json.dumps(route.response.message_type)},",
                    f"  responseMessageVersion: {route.response.message_version},",
                    f"  responseStream: {json.dumps(route.response.stream)},",
                    "} as const;",
                ]
            )
        )

    shared: list[NormalizedSchema] = []
    pending = list(messages)
    while pending:
        for field in pending.pop(0).fields:
            if field.ref_target is not None and field.ref_target.title not in {s.title for s in shared}:
                referenced = shared_by_title[field.ref_target.title]
                shared.append(referenced)
                pending.append(referenced)

    blocks = [
        "// Generated by xcore-protocol generators. Do not edit by hand.",
        *(_render_schema(schema) for schema in sorted(shared, key=lambda schema: schema.title)),
        *(_render_schema(schema) for schema in messages),
        *route_blocks,
    ]
    return "\n\n".join(blocks) + "\n"


def _render_schema(schema: NormalizedSchema) -> str:
    lines: list[str] = []
    for field in schema.fields:
        if field.enum_values:
            values_name = f"{_constant_name(field.enum_type_name or field.name, None)}_VALUES"
            lines.extend(
                [
                    f"export const {values_name} = [{', '.join(json.dumps(value) for value in field.enum_values)}] as const;",
                    f"export type {field.enum_type_name} = (typeof {values_name})[number];",
                    "",
                ]
            )
    lines.append(f"export interface {schema.title} {{")
    lines.extend(f"  {field.name}{'' if field.required else '?'}: {_field_type(field)};" for field in schema.fields)
    lines.append("}")
    return "\n".join(lines)


def _field_type(field: NormalizedField) -> str:
    if field.shape is not FieldShape.SCALAR:
        raise ValueError(f"TypeScript generation supports scalar fields only: {field.name}")
    if field.const is not None:
        return json.dumps(field.const)
    if field.enum_type_name is not None:
        return field.enum_type_name
    if field.field_type is FieldType.OBJECT_REF and field.ref_target is not None:
        return field.ref_target.title
    if field.field_type in _SCALAR_TYPES:
        return _SCALAR_TYPES[field.field_type]
    raise ValueError(f"Unsupported TypeScript field type for {field.name}: {field.field_type}")


def _constant_name(name: str, version: int | None) -> str:
    snake = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    snake = re.sub(r"[^A-Za-z0-9]+", "_", snake).upper()
    return snake if version is None else f"{snake}_V{version}"
