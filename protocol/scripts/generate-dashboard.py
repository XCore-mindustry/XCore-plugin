"""Render the protocol surface from canonical schemas and route manifests."""

from __future__ import annotations

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from generators.discovery import load_aggregate_generation_plan
from generators.families import FAMILY_CONFIGS
from generators.model import NormalizedSchema, load_shared_schema


def fields(schema: NormalizedSchema) -> str:
    required = [field.name for field in schema.fields if field.required]
    optional = [field.name for field in schema.fields if not field.required]
    parts = []
    if required:
        parts.append("required: " + ", ".join(required))
    if optional:
        parts.append("optional: " + ", ".join(optional))
    return "; ".join(parts)


def main() -> int:
    plan = load_aggregate_generation_plan()
    version = next(
        line.split('"')[1]
        for line in (REPO_ROOT / "pyproject.toml").read_text().splitlines()
        if line.startswith("version = ")
    )
    # Include authored shared types even when no current message references them.
    shared = [load_shared_schema(path) for path in sorted((REPO_ROOT / "spec/shared/types").glob("*.json"))]
    lines = [
        "# Protocol Surface Dashboard", "",
        "> Auto-generated by `scripts/generate-dashboard.py`. Do not edit manually.", "",
        "## Overview", "",
        f"- **Protocol Version:** {version}",
        f"- **Message Families:** {len(plan.family_inputs)}",
        f"- **Total Messages:** {sum(len(family.message_schemas) for family in plan.family_inputs)}",
        f"- **Total Routes:** {len(plan.route_descriptors)}",
        f"- **Shared Types:** {len(shared)}",
        f"- **Envelope Schemas:** {len(plan.envelope_schemas)}", "",
        "## Shared Types", "", "| Type | Fields |", "|------|--------|",
    ]
    lines.extend(f"| `{schema.title}` | {fields(schema)} |" for schema in shared)
    lines.extend(["", "## Envelope Schemas", "", "| Envelope | Fields |", "|----------|--------|"])
    lines.extend(f"| `{schema.title}` | {fields(schema)} |" for schema in plan.envelope_schemas)
    for family in plan.family_inputs:
        lines.extend(["", f"## {family.family.title()} Messages", "", "| Message | Schema File | Fields |", "|---------|-------------|--------|"])
        lines.extend(f"| `{schema.title}` | `{schema.schema_id}` | {fields(schema)} |" for schema in family.message_schemas)
    lines.extend(["", "## Route Manifest Summary", "", "| Message | Kind | Stream | TTL | Replayable | Response |", "|---------|------|--------|-----|------------|----------|"])
    for route in plan.route_descriptors:
        response = route.response.message.schema_title if route.response else "—"
        lines.append(f"| `{route.message.schema_title}` | {route.kind} | {route.stream} | {route.ttl_ms}ms | {route.replayable} | `{response}` |")
    lines.extend(["", "## Generated Artifacts", "", "| Language | Output Directory |", "|----------|------------------|"])
    for family in FAMILY_CONFIGS:
        lines.append(f"| Python | `python/xcore_protocol/generated/{family.python_module}.py` |")
        lines.append(f"| Java | `java/core/src/main/java/{family.java_package.replace('.', '/')}/` |")
    (REPO_ROOT / "PROTOCOL_SURFACE.md").write_text("\n".join(lines) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
